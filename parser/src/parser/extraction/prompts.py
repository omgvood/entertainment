"""Общие фрагменты системных промптов для LLM-экстракторов.

Вынесено сюда, чтобы правило по date='always' жило в одном месте, а не дублировалось
в каждом из трёх экстракторов (gemini/groq/deepseek) × двух промптах (single/batch).
"""

from __future__ import annotations

# Правило по date='always': запрещает LLM ставить 'always' для VK/Telegram/generic-постов
# без явной даты. Вставляется в SINGLE- и BATCH-промпты всех экстракторов.
DATE_ALWAYS_INSTRUCTIONS = """\
- `date='always'` разрешён ТОЛЬКО для постоянных заведений (боулинг, бильярд, картинг, квесты и т.п.) \
из direct_api-источников (twogis, quizplease), где события как такового нет — есть просто место.
- Для источников VK, Telegram и generic (посты/листинги, помеченные маркером «=== POST <url> ===») \
`date='always'` СТРОГО ЗАПРЕЩЁН. Если в тексте нет явной даты, дня недели или числа — \
пропусти это событие полностью (в batch-режиме просто не добавляй его в массив).
- Пример плохого поведения: «У нас каждую пятницу стендап в 19:00» → НЕ используй 'always'. \
Пропусти пост или укажи ближайшую конкретную дату, если она явно указана в тексте."""


# Правило «что не является событием» для batch-промптов: посты VK/Telegram идут через
# extract_many, а требование «верни ВСЕ события» толкало LLM делать событие из каждого поста
# с датой (новости городских пабликов, промо, розыгрыши). См. test_non_event.
NON_EVENT_INSTRUCTIONS = """\
- Посты и карточки, которые НЕ являются событиями, НЕ извлекай (в batch-режиме просто не \
добавляй их в массив). Событие — это то, куда человек может прийти в конкретное время: \
концерт, спектакль, выставка, ярмарка, мастер-класс, экскурсия, матч, праздник.
- НЕ события: новости и происшествия (аресты, суды, ДТП), законы и инициативы властей, \
объявления городских служб (парковки, ремонт дорог и мостов, перекрытия, транспорт), \
розыгрыши и конкурсы в соцсетях, промокоды, скидки и спецпредложения, голосования, \
приём заявок и open call, выход телепередач, итоги прошедших событий.
- Дата в тексте сама по себе не делает пост событием: «работы начнутся 20 сентября», \
«итоги розыгрыша 9 ноября», «акция до 30 сентября» → пропусти."""
